import type { RangeLike, SheetLike, SpreadsheetLike } from '../src/sheets/table';

/** Лист в памяти: двумерный массив, строки и колонки с 1, как в Apps Script. */
export class FakeSheet implements SheetLike {
  constructor(public cells: unknown[][]) {}
  getLastRow() {
    for (let r = this.cells.length; r > 0; r--)
      if (this.cells[r - 1]!.some((v) => v !== '' && v !== undefined)) return r;
    return 0;
  }
  getLastColumn() {
    return Math.max(0, ...this.cells.map((row) => row.length));
  }
  deleteRow(row: number) {
    this.cells.splice(row - 1, 1);
  }
  getRange(row: number, column: number, numRows: number, numColumns: number): RangeLike {
    return {
      getValues: () =>
        Array.from({ length: numRows }, (_, i) =>
          Array.from({ length: numColumns }, (_, j) => this.cells[row - 1 + i]?.[column - 1 + j] ?? ''),
        ),
      setValues: (values: unknown[][]) => {
        values.forEach((v, i) =>
          v.forEach((x, j) => {
            const r = row - 1 + i;
            while (this.cells.length <= r) this.cells.push([]);
            this.cells[r]![column - 1 + j] = x;
          }),
        );
      },
    };
  }
}

export class FakeSpreadsheet implements SpreadsheetLike {
  constructor(public sheets: Record<string, FakeSheet>) {}
  getSheetByName(name: string) {
    return this.sheets[name] ?? null;
  }
  insertSheet(name: string) {
    this.sheets[name] = new FakeSheet([]);
    return this.sheets[name]!;
  }
}

